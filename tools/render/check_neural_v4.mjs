import assert from 'node:assert/strict';
import fs from 'node:fs';
import {fcForward,cnnForward,rnnForward,FC_WEIGHTS} from '../../src/mv4/neural.js';
const fc=fcForward(),cat=cnnForward('cat'),star=cnnForward('star'),rnn=rnnForward();
